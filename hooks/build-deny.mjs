// Writes hooks/deny.json. The rules are regular expressions; composing them here keeps the JSON free of hand-escaped copies.
// Run: node hooks/build-deny.mjs
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

const r = String.raw;
// A command name counts only where a command can start, so the same words inside a commit message or an echo do not match.
export const AT = r`(?:^|[;&|(]\s*|\b(?:xargs|sudo|time|exec)\s+)`;
const ROOT = r`(?:/+\.?|/\*|[a-z]:[\\/]?|/[a-z]/?|/mnt/[a-z]/?)`;
const Q = r`["']?`;
const END = r`(?=\s|$|[;|&)])`;
const REST = r`[^;|&\n]*`;

const rules = [
  {
    id: 'root-find',
    // Windows find.exe takes /i "text": a quoted string after the switch is not a root search.
    command: r`${AT}find(?:\.exe)?\s+(?:-[HLP]+\s+|-O\d\s+|-D\s+\S+\s+)*(?:[^\s\-;|&][^\s;|&]*\s+)*${Q}${ROOT}${Q}${END}(?!\s+")`,
    reason: 'Recursive search from a filesystem root runs for hours and outlives the agent.',
    instead: 'search a named directory: the repo, or the folder that holds the target.',
  },
  {
    id: 'root-list',
    command: r`${AT}(?:Get-ChildItem|gci|dir)\b(?=${REST}\s-(?:r(?:ec\w*)?|Depth)\b)${REST}\s(?:-(?:Literal)?Path\s+)?${Q}(?:[a-z]:[\\/]?|\\\\|/)${Q}${END}`,
    reason: 'Recursive listing from a drive root runs for hours and outlives the agent.',
    instead: 'list a named directory: the repo, or the folder that holds the target.',
  },
  {
    id: 'root-ls',
    cs: true,
    command: r`${AT}ls\b(?=${REST}\s-[a-zA-Z]*R)${REST}\s${Q}(?:/+\.?|[A-Za-z]:[\\/]?|/[a-z]/?|/mnt/[a-z]/?)${Q}${END}`,
    reason: 'Recursive listing from a filesystem root runs for hours and outlives the agent.',
    instead: 'list a named directory: the repo, or the folder that holds the target.',
  },
  {
    id: 'root-grep',
    command: r`${AT}(?:rg|grep\b(?=${REST}\s(?:-[a-z]*r[a-z]*|--recursive|-d\s+recurse)\b))\b${REST}\s${Q}${ROOT}${Q}${END}`,
    reason: 'Recursive content search from a filesystem root runs for hours and outlives the agent.',
    instead: 'search a named directory: the repo, or the folder that holds the target.',
  },
  {
    id: 'root-cd',
    command: r`(?:^|[;&|(]\s*)(?:cd|pushd|Set-Location|sl)\s+${Q}${ROOT}${Q}\s*(?:;|&&|\|\||\n)[^\n]*\b(?:find|rg|grep\s+${REST}-[a-z]*r[a-z]*|ls\s+${REST}-[a-z]*r[a-z]*|(?:Get-ChildItem|gci)\b${REST}\s-r\w*|dir\s+${REST}/s)\b`,
    reason: 'Changing to a filesystem root and searching from there is the same root search.',
    instead: 'search a named directory: the repo, or the folder that holds the target.',
  },
  {
    id: 'narvai-allow',
    fixed: true,
    command: r`(?:^|[;&|(]\s*)(?:node(?:\.exe)?\s+)?${Q}[^\s"']*narvai(?:\.mjs|\.cmd)?${Q}\s+allow\b`,
    reason: 'Only the user lifts a guard rule.',
    instead: 'tell the user which rule stopped you and why you think an exception is right; they run narvai allow in their own terminal.',
  },
  {
    id: 'guard-files-shell',
    fixed: true,
    command: r`\.narvai[\\/](?:(?:allow|guard)\.json|guard\.log)`,
    reason: "The guard's rule, exception and log files are not edited directly.",
    instead: 'change the rules in their source and run narvai guard apply; an exception is the user\'s to grant.',
  },
  {
    id: 'guard-files-edit',
    fixed: true,
    tool: r`^(?:Edit|Write|MultiEdit|NotebookEdit|apply_patch)$`,
    path: r`(?:^|/)\.narvai/(?:(?:allow|guard)\.json|guard\.log)$`,
    reason: "The guard's rule, exception and log files are not edited directly.",
    instead: 'change the rules in their source and run narvai guard apply; an exception is the user\'s to grant.',
  },
];

if (process.argv[1] && process.argv[1].replace(/\\/g, '/').endsWith('hooks/build-deny.mjs')) {
  const about = 'Generated by hooks/build-deny.mjs; edit that file. The guard is a net for honest mistakes, not a sandbox: a command built to get past it will. A rule without `tool` applies to shell commands; with `tool` it applies to every tool whose name matches; `path` matches an edited file; `cs` makes it case-sensitive; `fixed` means no exception can lift it.';
  writeFileSync(join(import.meta.dirname, 'deny.json'), JSON.stringify({ about, rules }, null, 2) + '\n');
  console.log(`${rules.length} rules written`);
}
