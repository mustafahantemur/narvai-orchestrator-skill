import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { cfg, HARNESS } from './ortak.mjs';

const MARK = '# generated by narvai sync, edit agents/<name>.md in the harness repo';

// Codex has no documented model ids for these aliases: its model is left to the parent unless cfg().models sets one.
const DEFAULTS = {
  explore: { model: 'haiku', effort: 'low' },
  implement: { model: 'sonnet', effort: 'medium' },
  review: { model: 'opus', effort: 'high' },
};

export function modelFor(role, harness, models = cfg().models) {
  const base = DEFAULTS[role];
  if (!base) throw new Error(`unknown agent role "${role}": use ${Object.keys(DEFAULTS).join(', ')}`);
  return { ...(harness === 'claude' ? base : { effort: base.effort }), ...models?.[harness]?.[role] };
}

export function parseAgent(text) {
  const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n([\s\S]*)$/);
  if (!m) throw new Error('agent file has no frontmatter');
  const meta = {};
  for (const line of m[1].split(/\r?\n/)) {
    const kv = line.match(/^(\w+):\s*(.*)$/);
    if (kv) meta[kv[1]] = kv[2];
  }
  return { meta, body: m[2].trim() };
}

export function claudeFile({ meta, body }, { model, effort }) {
  const head = [
    `name: narvai-${meta.name}`,
    `description: ${JSON.stringify(meta.description)}`,
    meta.tools && `tools: ${meta.tools}`,
    model && `model: ${model}`,
    effort && `effort: ${effort}`,
    meta.omitRules === 'true' && 'omitClaudeMd: true',
    meta.skills && `skills: [${meta.skills}]`,
    MARK,
  ].filter(Boolean);
  return `---\n${head.join('\n')}\n---\n\n${body}\n`;
}

export function codexFile({ meta, body }, { model, effort }) {
  const instructions = body.includes("'''") ? JSON.stringify(body) : `'''\n${body}\n'''`;
  return [
    MARK,
    `name = "narvai-${meta.name}"`,
    `description = ${JSON.stringify(meta.description)}`,
    model && `model = ${JSON.stringify(model)}`,
    effort && `model_reasoning_effort = ${JSON.stringify(effort)}`,
    `developer_instructions = ${instructions}`,
  ].filter(Boolean).join('\n') + '\n';
}

function write(file, text) {
  if (existsSync(file) && !readFileSync(file, 'utf8').includes(MARK)) {
    console.log(`  WARN agent not written, not created by narvai: ${file}`);
    return false;
  }
  mkdirSync(join(file, '..'), { recursive: true });
  if (existsSync(file) && readFileSync(file, 'utf8') === text) return true;
  writeFileSync(file, text);
  console.log(`  OK   agent written: ${file}`);
  return true;
}

export async function emitAgents({ home }) {
  const dir = join(HARNESS, 'agents');
  const written = [];
  for (const f of existsSync(dir) ? readdirSync(dir).filter((n) => n.endsWith('.md')) : []) {
    const agent = parseAgent(readFileSync(join(dir, f), 'utf8'));
    const { name, role } = agent.meta;
    const targets = [
      [join(home, '.claude', 'agents', `narvai-${name}.md`), claudeFile(agent, modelFor(role, 'claude'))],
      [join(home, '.codex', 'agents', `narvai-${name}.toml`), codexFile(agent, modelFor(role, 'codex'))],
    ];
    for (const [file, text] of targets) if (write(file, text)) written.push(file);
  }
  return written;
}
