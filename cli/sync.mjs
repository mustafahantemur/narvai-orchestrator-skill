import { accessSync, constants, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { delimiter, dirname, join, resolve } from 'node:path';
import { backup, cfg, cfgPath, HARNESS, hermesHome, home, optional, sameDir } from './ortak.mjs';
import { linkSkills, pluginsOff } from './skills-link.mjs';

function writeGenerated(dst, body, adopt) {
  if (!existsSync(dirname(dst))) return;
  if (existsSync(dst)) {
    const cur = readFileSync(dst, 'utf8');
    if (cur === body) { console.log(`  OK   rules current: ${dst}`); return; }
    if (!/GENERATED by (setup-dev-harness|narvai)/.test(cur) && !adopt) {
      console.log(`  WARN ${dst} was not generated by narvai; left alone (rerun with --adopt to take it over, a backup is kept)`);
      return;
    }
  }
  backup(dst);
  writeFileSync(dst, body);
  console.log(`  OK   rules generated: ${dst}`);
}

const CLI = join(HARNESS, 'narvai.mjs').replace(/\\/g, '/');

// The rules name the bare command, so it has to resolve in every shell an agent uses: a POSIX script and, on Windows, a .cmd.
export function shim() {
  const onPath = (process.env.PATH ?? '').split(delimiter).filter(Boolean);
  const writable = (d) => { try { accessSync(d, constants.W_OK); return true; } catch { return false; } };
  const inHome = (d) => resolve(d).toLowerCase().startsWith(resolve(home()).toLowerCase());
  const found = [join(home(), '.local', 'bin'), ...onPath].find((d) => inHome(d) && onPath.some((p) => sameDir(p, d)) && writable(d));
  const dir = found ?? join(home(), '.narvai', 'bin');
  mkdirSync(dir, { recursive: true });
  const files = { narvai: `#!/bin/sh\nexec node "${CLI}" "$@"\n` };
  if (process.platform === 'win32') files['narvai.cmd'] = `@echo off\r\nnode "${CLI}" %*\r\n`;
  for (const [name, body] of Object.entries(files)) writeFileSync(join(dir, name), body, { mode: 0o755 });
  console.log(found ? `  OK   narvai command: ${dir}` : `  TODO narvai command written to ${dir}, which is not on PATH: add it`);
}

function nativeRoot() {
  const root = cfg().aiRoot;
  if (!root) throw new Error(`aiRoot is not set in ${cfgPath()}: run narvai setup`);
  return root.replace(/[\\/]/g, process.platform === 'win32' ? '\\' : '/');
}

// Every agent gets the same rendered rules; {{AI_ROOT}} becomes the configured root and
// {{MEMORY_PROJECT}} the single AgentMemory scope every repository shares.
function syncRules(adopt) {
  const read = (f) => readFileSync(f, 'utf8').replace(/\r\n/g, '\n')
    .replaceAll('{{AI_ROOT}}', nativeRoot).replaceAll('{{MEMORY_PROJECT}}', cfg().memoryProject ?? 'shared').replaceAll('{{NARVAI}}', `node "${CLI}"`).trimEnd();
  const rule = (f) => read(join(HARNESS, 'rules', f));
  const head = `<!-- GENERATED by narvai.mjs sync from rules/core.md + ~/.narvai/rules.md. Do not edit here. -->\n<!-- Edit the source, then rerun: node narvai.mjs sync -->\n\n`;
  const own = join(home(), '.narvai', 'rules.md');
  const rules = [rule('core.md'), existsSync(own) && read(own)].filter(Boolean).join('\n\n') + '\n';
  for (const dst of [join(home(), '.claude', 'CLAUDE.md'), join(home(), '.codex', 'AGENTS.md'), join(home(), '.gemini', 'config', 'GEMINI.md'), join(home(), '.pi', 'agent', 'AGENTS.md')]) {
    writeGenerated(dst, head + rules, adopt);
  }
  writeGenerated(join(hermesHome(), 'SOUL.md'), head + rule('hermes-identity.md') + '\n\n' + rules, adopt);
}

export default async function run(args = []) {
  console.log('narvai sync');
  const at = { home: home() };
  linkSkills();
  const tp = JSON.parse(readFileSync(join(HARNESS, 'third-party.json'), 'utf8'));
  pluginsOff(tp.plugins.off);
  syncRules(args.includes('--adopt'));
  shim();
  await (await optional('cli/agents-emit.mjs', 'emitAgents'))?.(at);
  await (await optional('hooks/register.mjs', 'registerHooks'))?.(at);
}
